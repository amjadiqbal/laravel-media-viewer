<?php

/*
 * Regenerates resources/integrity.php: the pinned versions of pdf.js and Video.js and a
 * sha384 hash for every browser file the runtime can load from them.
 *
 *   npm pack pdfjs-dist@6.4.299 @videojs/cdn@10.1.0   (in a scratch directory, then untar each)
 *   php scripts/build-integrity.php /path/to/pdfjs-dist/package /path/to/videojs-cdn/package
 *
 * Video.js entry files import shared chunks by relative URL, so the whole module graph
 * (static and dynamic imports) is walked from the three entries we load.
 */

[$self, $pdfjsDir, $videojsDir] = $argv + [null, null, null];

if (! $pdfjsDir || ! $videojsDir) {
    fwrite(STDERR, "usage: php {$self} <pdfjs-dist package dir> <@videojs/cdn package dir>\n");
    exit(1);
}

function sri(string $file): string
{
    return 'sha384-'.base64_encode(hash_file('sha384', $file, true));
}

function version(string $dir): string
{
    return json_decode(file_get_contents($dir.'/package.json'), true)['version'];
}

$pdfjs = [];
foreach (['build/pdf.min.mjs', 'build/pdf.worker.min.mjs', 'web/pdf_viewer.mjs', 'web/pdf_viewer.css'] as $file) {
    $pdfjs[$file] = sri($pdfjsDir.'/'.$file);
}

$videojs = [];
$walk = function (string $file) use (&$walk, &$videojs, $videojsDir): void {
    if (isset($videojs[$file])) {
        return;
    }
    $path = $videojsDir.'/'.$file;
    if (! is_file($path)) {
        throw new RuntimeException("Missing module {$file}");
    }
    $videojs[$file] = sri($path);
    $source = file_get_contents($path);
    preg_match_all('~(?:from\s*|import\s*)["\'](\.{1,2}/[^"\']+)["\']~', $source, $static);
    preg_match_all('~import\(\s*[`"\'](\.{1,2}/[^`"\']+)[`"\']~', $source, $dynamic);
    foreach (array_merge($static[1], $dynamic[1]) as $relative) {
        $parts = [];
        foreach (explode('/', dirname($file).'/'.$relative) as $part) {
            if ($part === '..') {
                array_pop($parts);
            } elseif ($part !== '.' && $part !== '') {
                $parts[] = $part;
            }
        }
        $walk(implode('/', $parts));
    }
};
foreach (['video.js', 'audio.js', 'media/hlsjs-video.js'] as $entry) {
    $walk($entry);
}
ksort($videojs);

$data = [
    'pdfjs' => ['package' => 'pdfjs-dist', 'version' => version($pdfjsDir), 'files' => $pdfjs],
    'videojs' => ['package' => '@videojs/cdn', 'version' => version($videojsDir), 'files' => $videojs],
];

$out = "<?php\n\n// Generated by scripts/build-integrity.php. Do not edit by hand.\n\nreturn ".var_export($data, true).";\n";
$out = str_replace(['array (', ')'], ['[', ']'], $out);
file_put_contents(__DIR__.'/../resources/integrity.php', $out);

printf("pdfjs-dist %s: %d files, @videojs/cdn %s: %d files\n", $data['pdfjs']['version'], count($pdfjs), $data['videojs']['version'], count($videojs));
